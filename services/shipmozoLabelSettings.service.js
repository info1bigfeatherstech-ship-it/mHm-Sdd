function mergeSection(defaults, incoming, spec) {
  const src = incoming && typeof incoming === 'object' ? incoming : {};
  const out = { ...defaults };
  for (const [key, kind] of Object.entries(spec)) {
    if (!Object.prototype.hasOwnProperty.call(src, key)) continue;
    if (kind === 'bool') out[key] = asBool(src[key], defaults[key]);
    else if (kind.type === 'int') out[key] = asInt(src[key], defaults[key], kind.min, kind.max);
    else if (kind.type === 'str') out[key] = asStr(src[key], kind.max);
  }
  return out;
}

function isAllowedLogoUrl(url) {
  const u = String(url || '').trim();
  if (!u) return false;
  try {
    const parsed = new URL(u);
    if (parsed.protocol !== 'https:') return false;
    return /(^|\.)cloudinary\.com$/i.test(parsed.hostname);
  } catch {
    return false;
  }
}

function sanitizeLogoUrl(url) {
  const u = asStr(url, 500);
  return isAllowedLogoUrl(u) ? u : '';
}

function mergeBranding(defaults, incoming, preserveAssets) {
  const src = incoming && typeof incoming === 'object' ? incoming : {};
  const out = { ...defaults };
  out.showLogo = asBool(src.showLogo, defaults.showLogo);
  if (preserveAssets) {
    out.logoUrl = sanitizeLogoUrl(preserveAssets.logoUrl);
    out.logoPublicId = asStr(preserveAssets.logoPublicId, 120);
  } else {
    out.logoUrl = sanitizeLogoUrl(src.logoUrl);
    out.logoPublicId = asStr(src.logoPublicId, 120);
    if (!out.logoUrl) out.logoPublicId = '';
  }
  return out;
}

/**
 * Normalize FE/admin aliases into canonical settings keys before sanitize.
 * Accepts nested `{ settings }` wrappers and legacy field names.
 */
function normalizeIncomingSettingsPatch(incoming) {
  let src = incoming && typeof incoming === 'object' ? { ...incoming } : {};
  if (src.settings && typeof src.settings === 'object') {
    src = { ...src.settings, ...src };
    delete src.settings;
  }

  const products = src.products && typeof src.products === 'object' ? { ...src.products } : src.products;
  if (products && products.maxLineItems == null && products.maxItems != null) {
    products.maxLineItems = products.maxItems;
  }

  let misc = src.misc && typeof src.misc === 'object' ? { ...src.misc } : null;
  const miscellaneous =
    src.miscellaneous && typeof src.miscellaneous === 'object' ? src.miscellaneous : null;
  if (!misc && miscellaneous) {
    misc = {
      ...miscellaneous,
      showEwayBill:
        miscellaneous.showEwayBill != null
          ? miscellaneous.showEwayBill
          : miscellaneous.showEwayBillNo,
      showPoweredBy:
        miscellaneous.showPoweredBy != null
          ? miscellaneous.showPoweredBy
          : miscellaneous.showPoweredByStore
    };
  } else if (misc && miscellaneous) {
    if (misc.showEwayBill == null && miscellaneous.showEwayBillNo != null) {
      misc.showEwayBill = miscellaneous.showEwayBillNo;
    }
    if (misc.showPoweredBy == null && miscellaneous.showPoweredByStore != null) {
      misc.showPoweredBy = miscellaneous.showPoweredByStore;
    }
  }

  let branding = src.branding && typeof src.branding === 'object' ? { ...src.branding } : null;
  const logo = src.logo && typeof src.logo === 'object' ? src.logo : null;
  if (!branding && logo) {
    branding = {
      showLogo: logo.enabled,
      logoUrl: logo.url,
      logoPublicId: logo.publicId || logo.logoPublicId || ''
    };
  } else if (branding && logo) {
    if (branding.showLogo == null && logo.enabled != null) branding.showLogo = logo.enabled;
    if (!branding.logoUrl && logo.url) branding.logoUrl = logo.url;
  }

  return {
    ...src,
    products,
    misc: misc || src.misc,
    branding: branding || src.branding
  };
}

/**
 * Sanitize a partial/full settings payload. Unknown keys dropped. Weight/dims stay on.
 */
function sanitizeSettings(incoming) {
  const d = defaultSettings();
  const src = normalizeIncomingSettingsPatch(incoming);
  try {
    return {
      labelSize: '4x6',
      support: mergeSection(d.support, src.support, {
        showCustomerSupport: 'bool',
        mobile: { type: 'str', max: 20 },
        email: { type: 'str', max: 120 }
      }),
      delivery: {
        ...mergeSection(d.delivery, src.delivery, {
          showPaymentMode: 'bool',
          showCustomerAddress: 'bool',
          showCustomerPhone: 'bool',
          showOrderBarcode: 'bool',
          showAwbBarcode: 'bool',
          showRoutingCode: 'bool',
          showRtoRoutingCode: 'bool',
          showDimension: 'bool',
          showWeight: 'bool'
        }),
        showDimension: true,
        showWeight: true
      },
      pickup: mergeSection(d.pickup, src.pickup, {
        showPickupName: 'bool',
        showPickupAddress: 'bool',
        showPickupPhone: 'bool',
        showRtoName: 'bool',
        showRtoAddress: 'bool',
        showGstin: 'bool',
        gstin: { type: 'str', max: 20 },
        sellerName: { type: 'str', max: 80 }
      }),
      products: mergeSection(d.products, src.products, {
        showItem: 'bool',
        showSku: 'bool',
        showQty: 'bool',
        showPrice: 'bool',
        showTotal: 'bool',
        showHsn: 'bool',
        showTaxableAmount: 'bool',
        showDiscount: 'bool',
        showPlatformFee: 'bool',
        showShippingCharges: 'bool',
        showCollectableAmount: 'bool',
        showTotalQuantity: 'bool',
        showAllItems: 'bool',
        trimSkuUpto: { type: 'int', min: 4, max: 40 },
        trimProductNameUpto: { type: 'int', min: 4, max: 40 },
        maxLineItems: { type: 'int', min: 1, max: 30 }
      }),
      misc: mergeSection(d.misc, src.misc, {
        showNotes: 'bool',
        notes: { type: 'str', max: 500 },
        showInvoiceNumber: 'bool',
        showInvoiceDate: 'bool',
        showOrderDate: 'bool',
        showOrderTotal: 'bool',
        showEwayBill: 'bool',
        showPoweredBy: 'bool',
        showAutoGeneratedDisclaimer: 'bool',
        showBorderToPageEnd: 'bool'
      }),
      branding: mergeBranding(d.branding, src.branding, null)
    };
  } catch (err) {
    logger.error('sanitizeSettings failed', { message: err?.message });
    return d;
  }
}

async function getOrCreateDoc(storefront) {
  const sf = normalizeStorefront(storefront);
  let doc = await ShipmozoLabelSettings.findOne({ storefront: sf });
  if (!doc) {
    doc = await ShipmozoLabelSettings.create({
      storefront: sf,
      settings: defaultSettings()
    });
  }
  return doc;
}

async function getPublicSettings(storefront) {
  const sf = normalizeStorefront(storefront);
  const doc = await getOrCreateDoc(sf);
  const settings = sanitizeSettings(doc.settings);
  return {
    storefront: sf,
    labelSize: '4x6',
    settings,
    updatedAt: doc.updatedAt || null
  };
}

async function saveSettings(storefront, patch, updatedBy) {
  const sf = normalizeStorefront(storefront);
  const existing = await getOrCreateDoc(sf);
  const prevBranding = existing.settings?.branding || defaultSettings().branding;
  const settings = sanitizeSettings(patch);
  settings.branding = mergeBranding(defaultSettings().branding, patch?.branding || {}, prevBranding);
  const doc = await ShipmozoLabelSettings.findOneAndUpdate(
    { storefront: sf },
    {
      $set: {
        settings,
        updatedBy: updatedBy || null
      }
    },
    { upsert: true, new: true, setDefaultsOnInsert: true }
  );
  return {
    storefront: sf,
    labelSize: '4x6',
    settings: sanitizeSettings(doc.settings),
    updatedAt: doc.updatedAt || null
  };
}

